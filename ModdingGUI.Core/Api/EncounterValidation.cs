namespace ModdingGUI.Core.Api;

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;
using ModdingGUI.Core.Tok.Values;

/// <summary>Severity of an encounter finding. Nothing here blocks a save.</summary>
public enum EncounterValidationSeverity
{
    /// <summary>Informational.</summary>
    Info,

    /// <summary>Something that will not behave as the modder expects.</summary>
    Warning,
}

/// <summary>Stable finding codes for encounters.</summary>
public static class EncounterValidationCodes
{
    /// <summary>A header key the corpus never uses; the engine ignores it.</summary>
    public const string UnknownHeaderKey = "unknown-header-key";

    /// <summary>A team key the corpus never uses.</summary>
    public const string UnknownTeamKey = "unknown-team-key";

    /// <summary>A <c>UNITDB</c> row with the wrong number of arguments.</summary>
    public const string UnitArgumentCount = "unit-argument-count";

    /// <summary>A team section with no <c>GRIDFILE</c>, so its units have no start grid.</summary>
    public const string TeamWithoutGrid = "team-without-grid";

    /// <summary>A team with no units at all.</summary>
    public const string EmptyTeam = "empty-team";

    /// <summary>No <c>ENCOUNTERNAME</c>, which leagues reference by name.</summary>
    public const string MissingName = "missing-encounter-name";

    /// <summary>The key is not in the engine's encounter field table, so it is ignored.</summary>
    public const string FieldNotInEngine = "field-not-in-engine";

    /// <summary>A <c>UNITDB</c> row has 21 values but one has the wrong type.</summary>
    public const string UnitShape = "unit-shape";

    /// <summary>The spawn chance is outside 0–100.</summary>
    public const string UnitSpawnChance = "unit-spawn-chance";

    /// <summary>The unit has no start slot, so it cannot be placed.</summary>
    public const string UnitStartSlot = "unit-start-slot";

    /// <summary>
    /// Two units of the same team share a start slot. The grid slot places one unit, so the
    /// second one is dropped at spawn time (confirmed in game: a moved unit disappeared).
    /// </summary>
    public const string DuplicateStartSlot = "duplicate-start-slot";

    /// <summary>The team's GRIDFILE does not resolve to a file in this project.</summary>
    public const string GridMissing = "grid-missing";

    /// <summary>The grid has no tag with the unit's start-slot name.</summary>
    public const string StartSlotUnknown = "start-slot-unknown";

    /// <summary>
    /// The grid names the tag but paints no cell with it. Each start slot paints exactly one cell
    /// in the vanilla grids, so an unpainted slot cannot place a unit at all.
    /// </summary>
    public const string StartSlotUnpainted = "start-slot-unpainted";

    /// <summary>
    /// More units share a start slot than the grid paints cells for it. Each painted cell places one
    /// unit, so the surplus is dropped at spawn time (observed in game).
    /// </summary>
    public const string StartSlotOverflow = "start-slot-overflow";

    /// <summary>The <c>TEAM</c> line's index does not parse, so the team cannot be identified.</summary>
    public const string TeamIndex = "team-index";

    /// <summary>
    /// The affinity requirement is not an engine affinity id. The matcher (<c>FUN_8010ad40</c>) compares it
    /// with the candidate unit's affinity byte, so anything outside -1 and 1-6 either excludes every unit
    /// or, with the prohibit flag set, excludes none of them.
    /// </summary>
    public const string AffinityRequirement = "affinity-requirement";
}

/// <summary>One finding about one encounter.</summary>
/// <param name="Severity">How much it matters.</param>
/// <param name="Code">Stable code from <see cref="EncounterValidationCodes"/>.</param>
/// <param name="Site">Where it applies, e.g. <c>header</c> or <c>team 1</c>.</param>
/// <param name="Key">Field it concerns, when applicable.</param>
/// <param name="Message">Human-readable explanation.</param>
public sealed record EncounterValidationIssue(
    EncounterValidationSeverity Severity,
    string Code,
    string Site,
    string? Key,
    string Message);

/// <summary>
/// Knowledge about encounter files: which header/team keys exist and how many arguments a
/// <c>UNITDB</c> row takes, generated by <c>encounters/build_catalog.py</c>.
/// </summary>
/// <remarks>
/// The engine skips keys it does not recognise, so a typo in a header silently does nothing;
/// the catalog is what lets the validator say so.
/// </remarks>
public sealed class EncountersCatalog
{
    /// <summary>Path, relative to the app directory, of the shipped catalog.</summary>
    public const string ShippedRelativePath = "encounters/encounters_catalog.json";

    private EncountersCatalog(
        IReadOnlyDictionary<string, int> headerKeys,
        IReadOnlyDictionary<string, int> teamKeys,
        IReadOnlyDictionary<string, int> engineKeys,
        IReadOnlyList<string> engineOnlyKeys,
        int unitArgumentCount,
        int fileCount)
    {
        HeaderKeys = headerKeys;
        TeamKeys = teamKeys;
        EngineKeys = engineKeys;
        EngineOnlyKeys = engineOnlyKeys;
        UnitArgumentCount = unitArgumentCount;
        FileCount = fileCount;
    }

    /// <summary>Header keys seen in the corpus with their frequencies.</summary>
    public IReadOnlyDictionary<string, int> HeaderKeys { get; }

    /// <summary>Per-team keys seen in the corpus with their frequencies.</summary>
    public IReadOnlyDictionary<string, int> TeamKeys { get; }

    /// <summary>
    /// The engine's own encounter key table (<c>EncounterSetup</c>, DOL <c>0x80106ddc</c>): key
    /// name to field id. Empty when the catalog predates the DOL merge.
    /// </summary>
    public IReadOnlyDictionary<string, int> EngineKeys { get; }

    /// <summary>Engine-legal keys the vanilla corpus never uses (e.g. <c>BLOCK</c>).</summary>
    public IReadOnlyList<string> EngineOnlyKeys { get; }

    /// <summary>Number of arguments a <c>UNITDB</c> row carries (21, from the DOL parser).</summary>
    public int UnitArgumentCount { get; }

    /// <summary>Encounter files the catalog was generated from.</summary>
    public int FileCount { get; }

    /// <summary>Load a catalog from an explicit path.</summary>
    public static EncountersCatalog Load(string path)
    {
        using var stream = File.OpenRead(path);
        return Load(stream);
    }

    /// <summary>Load a catalog from a stream.</summary>
    public static EncountersCatalog Load(Stream stream)
    {
        using var document = JsonDocument.Parse(stream);
        var root = document.RootElement;

        var headerKeys = ReadCounts(root, "header_keys");
        var teamKeys = ReadCounts(root, "team_keys");
        var engineKeys = ReadEngineKeys(root, "engine_keys");

        int unitArity = 21;
        int fileCount = 0;
        if (root.TryGetProperty("_meta", out var meta))
        {
            if (meta.TryGetProperty("unit_arity", out var arity) && arity.ValueKind == JsonValueKind.Object)
            {
                var most = arity.EnumerateObject()
                    .Where(p => p.Value.ValueKind == JsonValueKind.Number)
                    .OrderByDescending(p => p.Value.GetInt32())
                    .FirstOrDefault();
                if (most.Name.Length > 0) unitArity = int.Parse(most.Name);
            }
            if (meta.TryGetProperty("totals", out var totals)
                && totals.TryGetProperty("files", out var files)
                && files.ValueKind == JsonValueKind.Number)
            {
                fileCount = files.GetInt32();
            }
        }

        var engineOnly = ReadEngineOnly(root);

        return new EncountersCatalog(headerKeys, teamKeys, engineKeys, engineOnly, unitArity, fileCount);
    }

    /// <summary>Load the shipped catalog, or null when the file is not deployed.</summary>
    public static EncountersCatalog? Shipped()
    {
        foreach (string candidate in Candidates())
        {
            if (File.Exists(candidate)) return Load(candidate);
        }
        return null;
    }

    private static IEnumerable<string> Candidates()
    {
        yield return Path.Combine(AppContext.BaseDirectory,
            ShippedRelativePath.Replace('/', Path.DirectorySeparatorChar));

        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        for (int i = 0; i < 6 && dir is not null; i++, dir = dir.Parent)
        {
            yield return Path.Combine(dir.FullName,
                ShippedRelativePath.Replace('/', Path.DirectorySeparatorChar));
        }
    }

    private static IReadOnlyDictionary<string, int> ReadEngineKeys(JsonElement root, string property)
    {
        var result = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        if (!root.TryGetProperty(property, out var element) || element.ValueKind != JsonValueKind.Object)
            return result;

        foreach (var pair in element.EnumerateObject())
        {
            if (pair.Value.ValueKind == JsonValueKind.Object
                && pair.Value.TryGetProperty("id", out var id)
                && id.ValueKind == JsonValueKind.Number)
            {
                result[pair.Name] = id.GetInt32();
            }
        }
        return result;
    }

    private static IReadOnlyList<string> ReadEngineOnly(JsonElement root)
    {
        if (!root.TryGetProperty("_meta", out var meta)
            || !meta.TryGetProperty("engine", out var engine)
            || !engine.TryGetProperty("engine_only", out var only)
            || only.ValueKind != JsonValueKind.Array)
        {
            return Array.Empty<string>();
        }

        return only.EnumerateArray()
            .Where(v => v.ValueKind == JsonValueKind.String)
            .Select(v => v.GetString()!)
            .ToArray();
    }

    private static IReadOnlyDictionary<string, int> ReadCounts(JsonElement root, string property)
    {
        var result = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        if (!root.TryGetProperty(property, out var element) || element.ValueKind != JsonValueKind.Object)
            return result;

        foreach (var pair in element.EnumerateObject())
        {
            result[pair.Name] = pair.Value.ValueKind == JsonValueKind.Number ? pair.Value.GetInt32() : 0;
        }
        return result;
    }
}

/// <summary>Advisory checks for one encounter.</summary>
public static class EncounterValidator
{
    /// <summary>Validate a parsed encounter against the catalog (a null catalog skips key checks).</summary>
    /// <param name="encounter">Parsed encounter.</param>
    /// <param name="catalog">Key catalog, or null to skip key checks.</param>
    /// <param name="gridResolver">
    /// Loads a team's grid from its <c>GRIDFILE</c> value. Pass null to skip grid checks; the
    /// encounter API supplies one that resolves <c>$d</c>/<c>$l</c> against the project.
    /// </param>
    public static IReadOnlyList<EncounterValidationIssue> Validate(
        EncounterDto encounter,
        EncountersCatalog? catalog,
        Func<string, Grids.GridFile?>? gridResolver = null)
    {
        ArgumentNullException.ThrowIfNull(encounter);

        var issues = new List<EncounterValidationIssue>();

        if (encounter.Value("ENCOUNTERNAME") is null)
        {
            issues.Add(new EncounterValidationIssue(
                EncounterValidationSeverity.Warning,
                EncounterValidationCodes.MissingName, "header", "ENCOUNTERNAME",
                "no ENCOUNTERNAME; leagues reference encounters by this name"));
        }

        if (catalog is not null)
        {
            foreach (var field in encounter.Fields)
            {
                if (!catalog.HeaderKeys.ContainsKey(field.Key))
                {
                    issues.Add(new EncounterValidationIssue(
                        EncounterValidationSeverity.Warning,
                        EncounterValidationCodes.UnknownHeaderKey, "header", field.Key,
                        $"'{field.Key}' is not a known encounter header key; the game ignores it"));
                }
                else if (catalog.EngineKeys.Count > 0 && !catalog.EngineKeys.ContainsKey(field.Key))
                {
                    issues.Add(new EncounterValidationIssue(
                        EncounterValidationSeverity.Warning,
                        EncounterValidationCodes.FieldNotInEngine, "header", field.Key,
                        $"'{field.Key}' is not in the engine's encounter field table"));
                }
            }
        }

        if (encounter.Teams.Count == 0)
        {
            issues.Add(new EncounterValidationIssue(
                EncounterValidationSeverity.Warning,
                EncounterValidationCodes.EmptyTeam, "file", null,
                "the encounter has no TEAM sections"));
        }

        foreach (var team in encounter.Teams)
        {
            string site = $"{encounter.Name} team {team.Index}";

            if (catalog is not null)
            {
                foreach (var field in team.Fields)
                {
                    if (!catalog.TeamKeys.ContainsKey(field.Key))
                    {
                        issues.Add(new EncounterValidationIssue(
                            EncounterValidationSeverity.Warning,
                            EncounterValidationCodes.UnknownTeamKey, site, field.Key,
                            $"'{field.Key}' is not a known team key; the game ignores it"));
                    }
                    else if (catalog.EngineKeys.Count > 0 && !catalog.EngineKeys.ContainsKey(field.Key))
                    {
                        issues.Add(new EncounterValidationIssue(
                            EncounterValidationSeverity.Warning,
                            EncounterValidationCodes.FieldNotInEngine, site, field.Key,
                            $"'{field.Key}' is not in the engine's encounter field table"));
                    }
                }
            }

            Grids.GridFile? grid = null;
            string? gridFile = team.Value("GRIDFILE");
            if (gridFile is null)
            {
                issues.Add(new EncounterValidationIssue(
                    EncounterValidationSeverity.Warning,
                    EncounterValidationCodes.TeamWithoutGrid, site, "GRIDFILE",
                    "team has no GRIDFILE, so its UNITDB start slots cannot resolve"));
            }
            else if (gridResolver is not null)
            {
                grid = gridResolver(gridFile);
                if (grid is null)
                {
                    issues.Add(new EncounterValidationIssue(
                        EncounterValidationSeverity.Warning,
                        EncounterValidationCodes.GridMissing, site, "GRIDFILE",
                        $"GRIDFILE '{gridFile.Trim().Trim('"')}' does not resolve to a file in this project"));
                }
            }

            // Which tags the grid actually paints. A slot with no painted cell cannot place a unit.
            Dictionary<string, int>? cellsPerTag = grid is null ? null : CellsPerTag(grid);

            if (team.Units.Count == 0)
            {
                issues.Add(new EncounterValidationIssue(
                    EncounterValidationSeverity.Info,
                    EncounterValidationCodes.EmptyTeam, site, null,
                    "team has no UNITDB rows"));
            }

            var startSlots = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            var namedOnSlot = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);

            for (int i = 0; i < team.Units.Count; i++)
            {
                string raw = team.Units[i];
                int count = CountArguments(raw);
                string where = $"{site}, unit {i + 1}";

                if (catalog is not null && count != catalog.UnitArgumentCount)
                {
                    issues.Add(new EncounterValidationIssue(
                        EncounterValidationSeverity.Warning,
                        EncounterValidationCodes.UnitArgumentCount, where, "UNITDB",
                        $"{count} arguments; the engine reads {catalog.UnitArgumentCount} " +
                        "(string, int, string, int×5, string×4, int×12)"));
                    continue;
                }

                var unit = EncounterUnit.TryParse(raw);
                if (unit is null)
                {
                    issues.Add(new EncounterValidationIssue(
                        EncounterValidationSeverity.Warning,
                        EncounterValidationCodes.UnitShape, where, "UNITDB",
                        "a value has the wrong type for its slot; the engine aborts the record"));
                    continue;
                }

                // The engine tests (rand % 100) + 1 <= value, so 100 or more always spawns (the
                // corpus even contains 1000); only a negative value is meaningless.
                if (unit.SpawnChancePercent < 0)
                {
                    issues.Add(new EncounterValidationIssue(
                        EncounterValidationSeverity.Warning,
                        EncounterValidationCodes.UnitSpawnChance, where, "UNITDB",
                        $"spawn chance {unit.SpawnChancePercent} is negative"));
                }

                if (string.IsNullOrWhiteSpace(unit.StartSlot))
                {
                    issues.Add(new EncounterValidationIssue(
                        EncounterValidationSeverity.Warning,
                        EncounterValidationCodes.UnitStartSlot, where, "UNITDB",
                        "unit has no start slot, so it cannot be placed on the grid"));
                }
                else if (cellsPerTag is not null && !cellsPerTag.ContainsKey(unit.StartSlot))
                {
                    bool tagExists = Enumerable.Range(0, Grids.GridFile.NumSlots)
                        .Any(slot => string.Equals(grid!.GetTagNameForSlot(slot), unit.StartSlot,
                                                       StringComparison.OrdinalIgnoreCase));

                    // Info, not a warning: 72 vanilla units sit on slots their grid does not paint,
                    // on maps that demonstrably work, so the data alone cannot decide whether this is
                    // broken. It is still worth surfacing - an unpainted slot is a plausible cause of
                    // a unit silently failing to spawn.
                    issues.Add(new EncounterValidationIssue(
                        EncounterValidationSeverity.Info,
                        tagExists ? EncounterValidationCodes.StartSlotUnpainted
                                  : EncounterValidationCodes.StartSlotUnknown,
                        where, "UNITDB",
                        tagExists
                            ? $"start slot '{unit.StartSlot}' is not painted on the team grid"
                            : $"start slot '{unit.StartSlot}' is not a tag on the team grid"));
                }
                else if (startSlots.TryGetValue(unit.StartSlot, out int alreadyTakenBy))
                {
                    // Vanilla shares slots freely (4171 cases, 340 between named units), so this is
                    // information, not an error. It is still worth surfacing: a QA build that moved
                    // a named unit onto an occupied slot lost that unit in game, and only checking in
                    // game will tell whether it is the slot or something else.
                    // Only worth reporting when a *named* unit has to share, because that is where a unit can go missing.
                    // Unnamed rows on one marker are ordinary: the engine places them on random cells of that marker, and
                    // vanilla content does it constantly (Battle1 of the Pirgos open league puts three rows on Start1).
                    if (unit.UnitName.Length > 0 || namedOnSlot.ContainsKey(unit.StartSlot))
                    {
                        issues.Add(new EncounterValidationIssue(
                            EncounterValidationSeverity.Info,
                            EncounterValidationCodes.DuplicateStartSlot, where, "UNITDB",
                            $"start slot '{unit.StartSlot}' is also used by unit {alreadyTakenBy + 1}"));
                    }
                }
                else
                {
                    startSlots[unit.StartSlot] = i;
                    if (unit.UnitName.Length > 0) namedOnSlot[unit.StartSlot] = i;
                }
            }

            // Team -1 is the neutral team (summoned creatures): one vanilla encounter puts four of them
            // on a two-cell slot and works, so capacity is only enforced for the player and enemy teams.
            if (cellsPerTag is not null && team.Index >= 0)
            {
                foreach (var (slot, count) in UnitCountsPerSlot(team))
                {
                    if (!cellsPerTag.TryGetValue(slot, out int cells)) continue;

                    if (count > cells)
                    {
                        issues.Add(new EncounterValidationIssue(
                            EncounterValidationSeverity.Warning,
                            EncounterValidationCodes.StartSlotOverflow, site, "UNITDB",
                            $"{count} units share start slot '{slot}' but the grid paints only {cells} " +
                            $"cell(s) for it; the surplus cannot be placed"));
                    }
                }
            }

            // The affinity requirement is compared with the candidate unit's affinity byte by FUN_8010ad40,
            // so a value outside the engine ids can never match anything.
            foreach (string raw in team.Units)
            {
                var unit = EncounterUnit.TryParse(raw);
                if (unit is null) continue;

                int required = unit.AffinityRequirement;
                if (required is < -1 or > 6)
                {
                    issues.Add(new EncounterValidationIssue(
                        EncounterValidationSeverity.Warning,
                        EncounterValidationCodes.AffinityRequirement, site, "UNITDB",
                        $"affinity requirement {required} is not an engine affinity id " +
                        "(-1 = none, 1 Earth, 2 Water, 3 Dark, 4 Air, 5 Fire, 6 Light)"));
                }
            }
        }

        return issues;
    }

    /// <summary>How many cells the grid paints for each tag name.</summary>
    private static Dictionary<string, int> CellsPerTag(Grids.GridFile grid)
    {
        var counts = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);

        for (int slot = 0; slot < Grids.GridFile.NumSlots; slot++)
        {
            string tag = grid.GetTagNameForSlot(slot);
            if (string.IsNullOrWhiteSpace(tag) || tag == Grids.GridFile.NO_VALUE) continue;

            int bit = 1 << slot;
            int cells = 0;
            for (int row = 0; row < Grids.GridFile.ArenaSize; row++)
            {
                for (int col = 0; col < Grids.GridFile.ArenaSize; col++)
                {
                    if ((grid.GetValue(row, col) & bit) != 0) cells++;
                }
            }

            if (cells > 0) counts[tag] = cells;
        }

        return counts;
    }

    /// <summary>How many units of a team sit on each start slot.</summary>
    private static Dictionary<string, int> UnitCountsPerSlot(EncounterTeamDto team)
    {
        var counts = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        foreach (string raw in team.Units)
        {
            var unit = EncounterUnit.TryParse(raw);
            if (unit is null || string.IsNullOrWhiteSpace(unit.StartSlot)) continue;

            // Only named units need their own cell: an empty name means "generate one from the team's
            // school", and those are auto-placed (four vanilla encounters share a 1-cell slot between
            // three or four generated units). A named unit with nowhere to stand is dropped instead.
            if (string.IsNullOrWhiteSpace(unit.UnitName)) continue;

            counts[unit.StartSlot] = counts.TryGetValue(unit.StartSlot, out int seen) ? seen + 1 : 1;
        }
        return counts;
    }

    /// <summary>Count comma-separated arguments, ignoring empty slots.</summary>
    internal static int CountArguments(string raw) =>
        TokValueReader.Parse(raw).Tokens.Count(t => t.Kind != TokValueKind.Empty);
}
