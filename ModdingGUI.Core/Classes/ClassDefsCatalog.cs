namespace ModdingGUI.Core.Classes;

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.Json;

/// <summary>One argument position of a classdefs field, e.g. the category of <c>ITEMCAT</c>.</summary>
public sealed class ClassSlotSpec
{
    /// <summary>Token kinds observed at this position (<c>string</c>, <c>int</c>, <c>float</c>).</summary>
    public IReadOnlyList<string> Types { get; init; } = Array.Empty<string>();

    /// <summary>Distinct bare-word values observed at this position (empty when not enumerable).</summary>
    public IReadOnlyList<string> Values { get; init; } = Array.Empty<string>();

    /// <summary>True when the catalog knows at least one value for this position.</summary>
    public bool IsEnumerable => Values.Count > 0;

    /// <summary>True when <paramref name="text"/> is a documented value (case-insensitive).</summary>
    public bool Allows(string text) =>
        Values.Any(v => string.Equals(v, text, StringComparison.OrdinalIgnoreCase))
        || string.Equals(text, "<Any>", StringComparison.OrdinalIgnoreCase);
}

/// <summary>Catalog knowledge about one <c>classdefs.tok</c> key.</summary>
public sealed class ClassFieldSpec
{
    /// <summary>Field name as written in the file, upper-case.</summary>
    public string Name { get; init; } = string.Empty;

    /// <summary>True when the game's own field table contains this key.</summary>
    public bool EngineKnown { get; init; }

    /// <summary>Id the engine's tokenizer assigns to this key, when known.</summary>
    public int? EngineId { get; init; }

    /// <summary>True when the corpus repeats this key inside a block (<c>ATTRIBUTE</c>, <c>ITEMCAT</c>, …).</summary>
    public bool Multi { get; init; }

    /// <summary>Highest occurrence count seen in one class block.</summary>
    public int MaxOccurrences { get; init; } = 1;

    /// <summary>Number of argument positions.</summary>
    public int Arity { get; init; }

    /// <summary>Per-position shapes and observed values.</summary>
    public IReadOnlyList<ClassSlotSpec> Slots { get; init; } = Array.Empty<ClassSlotSpec>();

    /// <summary>True for engine-legal keys the vanilla corpus never uses.</summary>
    public bool EngineOnly { get; init; }

    /// <summary>How many class blocks use this key.</summary>
    public int ClassesUsing { get; init; }

    /// <summary>True when repeating the key inside one block is legal.</summary>
    public bool AllowsRepetition => Multi || (EngineKnown && MaxOccurrences > 1);
}

/// <summary>Summary of one class, enough to list and inspect without re-parsing the file.</summary>
public sealed class ClassInfo
{
    /// <summary>Class name as written after <c>CREATECLASS:</c>.</summary>
    public string Name { get; init; } = string.Empty;

    /// <summary>Lookup text id used for the class's display name.</summary>
    public int? DisplayNameId { get; init; }

    /// <summary>Lookup text id used for the class description.</summary>
    public int? DescriptionId { get; init; }

    /// <summary>Mesh name the class renders with.</summary>
    public string? Mesh { get; init; }

    /// <summary>Name of the skill set the class uses.</summary>
    public string? SkillUseName { get; init; }

    /// <summary>Keys this class's block contains.</summary>
    public IReadOnlyList<string> Keys { get; init; } = Array.Empty<string>();
}

/// <summary>
/// Knowledge about <c>classdefs.tok</c>, generated by <c>classdefs/build_catalog.py</c> from
/// the corpus and the engine's own field table (<c>dol/classdefs_fields.json</c>).
/// </summary>
/// <remarks>
/// Like the skills catalog this is data, not code: it carries the argument shapes and
/// enumerations the file uses plus the engine's verdict on which keys exist at all
/// (the engine silently ignores unknown keys, so a catalog is the only way to warn).
/// </remarks>
public sealed class ClassDefsCatalog
{
    /// <summary>Path, relative to the app directory, of the shipped catalog.</summary>
    public const string ShippedRelativePath = "classdefs/classdefs_catalog.json";

    private readonly Dictionary<string, ClassFieldSpec> _fields;
    private readonly Dictionary<string, ClassInfo> _classes;

    private ClassDefsCatalog(
        Dictionary<string, ClassFieldSpec> fields,
        Dictionary<string, ClassInfo> classes,
        ClassDefsCatalogMeta meta)
    {
        _fields = fields;
        _classes = classes;
        Meta = meta;
    }

    /// <summary>Generation metadata (source file, engine coverage).</summary>
    public ClassDefsCatalogMeta Meta { get; }

    /// <summary>All known fields, keyed by upper-case name.</summary>
    public IReadOnlyDictionary<string, ClassFieldSpec> Fields => _fields;

    /// <summary>All known classes, keyed by name.</summary>
    public IReadOnlyDictionary<string, ClassInfo> Classes => _classes;

    /// <summary>Find a field by name (case-insensitive).</summary>
    public ClassFieldSpec? Find(string fieldName) =>
        fieldName is not null && _fields.TryGetValue(NormalizeKey(fieldName), out var spec) ? spec : null;

    /// <summary>Find a class by name (case-sensitive, as the game treats names as literal).</summary>
    public ClassInfo? FindClass(string className) =>
        className is not null && _classes.TryGetValue(className, out var info) ? info : null;

    /// <summary>Canonical field key form used by the catalog.</summary>
    public static string NormalizeKey(string fieldName) => fieldName.Trim().ToUpperInvariant();

    /// <summary>Load a catalog from an explicit path.</summary>
    public static ClassDefsCatalog Load(string path)
    {
        using var stream = File.OpenRead(path);
        return Load(stream);
    }

    /// <summary>Load a catalog from a stream.</summary>
    public static ClassDefsCatalog Load(Stream stream)
    {
        using var document = JsonDocument.Parse(stream);
        var root = document.RootElement;

        var fields = new Dictionary<string, ClassFieldSpec>(StringComparer.OrdinalIgnoreCase);
        if (root.TryGetProperty("fields", out var fieldsElement))
        {
            foreach (var property in fieldsElement.EnumerateObject())
            {
                var spec = ParseField(property.Name, property.Value);
                if (spec is not null) fields[spec.Name] = spec;
            }
        }

        var classes = new Dictionary<string, ClassInfo>(StringComparer.Ordinal);
        if (root.TryGetProperty("classes", out var classesElement))
        {
            foreach (var property in classesElement.EnumerateObject())
            {
                classes[property.Name] = ParseClass(property.Name, property.Value);
            }
        }

        var meta = new ClassDefsCatalogMeta();
        if (root.TryGetProperty("_meta", out var metaElement))
        {
            meta = new ClassDefsCatalogMeta
            {
                FormatVersion = ReadInt(metaElement, "format_version") ?? 1,
                ClassCount = ReadInt(metaElement, "class_count") ?? classes.Count,
            };
        }

        return new ClassDefsCatalog(fields, classes, meta);
    }

    /// <summary>
    /// Load the catalog shipped next to the application, falling back to the repository
    /// layout when running from a test or tool directory.
    /// </summary>
    public static ClassDefsCatalog Shipped()
    {
        string? path = ShippedPath();
        if (path is null)
            throw new FileNotFoundException(
                $"classdefs catalog not found (looked for {ShippedRelativePath}).");

        return Load(path);
    }

    /// <summary>Locate the shipped catalog, or null when it cannot be found.</summary>
    public static string? ShippedPath()
    {
        var candidates = new List<string>
        {
            Path.Combine(AppContext.BaseDirectory, ShippedRelativePath.Replace('/', Path.DirectorySeparatorChar)),
        };

        // Walk up from the test/tool bin directory to the repository copy.
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        for (int i = 0; i < 6 && dir is not null; i++, dir = dir.Parent)
        {
            candidates.Add(Path.Combine(dir.FullName, ShippedRelativePath.Replace('/', Path.DirectorySeparatorChar)));
        }

        return candidates.FirstOrDefault(File.Exists);
    }

    private static ClassFieldSpec? ParseField(string name, JsonElement element)
    {
        try
        {
            var slots = new List<ClassSlotSpec>();
            if (element.TryGetProperty("slots", out var slotsElement)
                && slotsElement.ValueKind == JsonValueKind.Array)
            {
                foreach (var slot in slotsElement.EnumerateArray())
                {
                    slots.Add(new ClassSlotSpec
                    {
                        Types = ReadStrings(slot, "types"),
                        Values = ReadStrings(slot, "values"),
                    });
                }
            }

            return new ClassFieldSpec
            {
                Name = NormalizeKey(name),
                EngineKnown = ReadBool(element, "engine") ?? false,
                EngineId = ReadInt(element, "engine_id"),
                Multi = ReadBool(element, "multi") ?? false,
                MaxOccurrences = ReadInt(element, "max_occurrences") ?? 1,
                Arity = ReadInt(element, "arity") ?? slots.Count,
                Slots = slots,
                EngineOnly = ReadBool(element, "engine_only") ?? false,
                ClassesUsing = ReadInt(element, "classes_using") ?? 0,
            };
        }
        catch (InvalidOperationException)
        {
            return null;
        }
    }

    private static ClassInfo ParseClass(string name, JsonElement element) => new()
    {
        Name = name,
        DisplayNameId = ReadInt(element, "displayNameId"),
        DescriptionId = ReadInt(element, "descriptionId"),
        Mesh = ReadString(element, "mesh"),
        SkillUseName = ReadString(element, "skillUseName"),
        Keys = ReadStrings(element, "keys"),
    };

    private static IReadOnlyList<string> ReadStrings(JsonElement element, string property)
    {
        if (!element.TryGetProperty(property, out var value) || value.ValueKind != JsonValueKind.Array)
            return Array.Empty<string>();

        return value.EnumerateArray()
            .Where(v => v.ValueKind == JsonValueKind.String)
            .Select(v => v.GetString()!)
            .ToArray();
    }

    private static string? ReadString(JsonElement element, string property) =>
        element.TryGetProperty(property, out var value) && value.ValueKind == JsonValueKind.String
            ? value.GetString()
            : null;

    private static int? ReadInt(JsonElement element, string property) =>
        element.TryGetProperty(property, out var value) && value.ValueKind == JsonValueKind.Number
            && value.TryGetInt32(out int result)
            ? result
            : null;

    private static bool? ReadBool(JsonElement element, string property) =>
        element.TryGetProperty(property, out var value)
        && value.ValueKind is JsonValueKind.True or JsonValueKind.False
            ? value.GetBoolean()
            : null;
}

/// <summary>Generation metadata for a <see cref="ClassDefsCatalog"/>.</summary>
public sealed class ClassDefsCatalogMeta
{
    /// <summary>Catalog format version.</summary>
    public int FormatVersion { get; init; } = 1;

    /// <summary>Class blocks the generator saw.</summary>
    public int ClassCount { get; init; }
}
