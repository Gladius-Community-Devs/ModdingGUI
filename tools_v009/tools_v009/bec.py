"""BEC archive pack/unpack.

The Gladius ``.bec`` container format: a small header, a table of 16-byte file
entries (path hash, data offset, compressed size, data size), then the payload
region.  Files are stored either raw or zlib-compressed (PS2/Xbox); each stored
file is followed by an 8-byte checksum (CRC-32 reflected ``0xEDB88320``,
init=0, no final XOR) padded to the archive's file alignment.
"""

