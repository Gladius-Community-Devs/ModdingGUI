def getAlignment(pos, align):
    if (pos % align) > 0:
        return (align - (pos % align))
    return 0


class RomSection:
    def __init__(self, name, hash, address, compressedSize, size):
        self.FileName = name.replace("\\", "/").lower()
        self.PathHash = int(hash)
        if self.PathHash == 0:
            self.PathHash = computeFileHash(self.FileName)

        self.DataOffset = int(address)
        self.OriginalDataOffset = self.DataOffset
        self.DataSize = int(size)
        self.CompressedSize = int(compressedSize)

        self.IsNew = False
        self.IsDuplicate = ((int(compressedSize) & duplicateFlag) != 0)

    @classmethod
    def fromList(cls, data):
        return cls(data[0], data[1], data[2], data[3], data[4])

    def unpackedCompressedSize(self):
        return self.CompressedSize & (~duplicateFlag)

    def storedSize(self):
        if self.unpackedCompressedSize() != 0:
            return self.unpackedCompressedSize()
        return self.DataSize


