def _unpack_section(bec_filename, filedir, romSection):
    with open(bec_filename, "rb") as f:
        fileByteArray = ReadSection(f, romSection.DataOffset, romSection.DataSize)
    localByteArray = bytearray(fileByteArray)
    if len(localByteArray) > 0 and localByteArray[0] == 0x78:
        localByteArray = zlib.decompress(fileByteArray)
    WriteSectionInFile(localByteArray, filedir, romSection.FileName)
    return len(localByteArray)


def unpackBecArchive(filename, filedir, demobec=False, platform="GC", num_threads=None):
    print("Platform is : " + platform)
    print("Filename : " + filename)
    print("Filedir : " + filedir)
    if not filedir.endswith(("/", "\\")):
        filedir += "/"
    with open(filename, "rb") as file:
        header_output = unpackBecArchive2(file, filename, filedir, demobec, num_threads)

    headerfilename = filedir + headerFile
    if not os.path.exists(os.path.dirname(headerfilename)) and os.path.dirname(headerfilename):
        os.makedirs(os.path.dirname(headerfilename))
    with open(headerfilename, "w") as fheader:
        fheader.write(header_output)


def unpackBecArchive2(file, bec_filename, filedir, demobec, num_threads=None):
    output = ""
    RomSections = []

    totalUnpacked = 0
    totalDuplicates = 0
    totalUnknown = 0

    if num_threads is None:
        num_threads = NUM_THREADS

    BecHeader = namedtuple("BecHeader", ["FileAlignment", "NrOfFiles", "HeaderMagic"])

    if demobec:
        file.seek(0x4)
        data = file.read(4)
        numFiles = struct.unpack("<I", data)[0]
        makeData = [0, numFiles, 0]
        header = BecHeader._make(makeData)
    else:
        file.seek(0x6)
        data = file.read(10)
        header = BecHeader._make(struct.unpack("<HII", data))

    print("Nr of Files in the bec-file: " + str(header.NrOfFiles))
    print("File Alignment: " + str(header.FileAlignment))
    output += str(header.FileAlignment) + separator + str(header.NrOfFiles) + separator + str(header.HeaderMagic) + "\n"

    count = 0
    FileEntry = namedtuple("FileEntry", ["PathHash", "DataOffset", "CompDataSize", "DataSize"])
    for i in range(header.NrOfFiles):
        data = file.read(0x10)
        fileEntry = FileEntry._make(struct.unpack("<IIII", data))
        filename = getFilename(fileEntry.PathHash, count)
        if filename.startswith("unknown-"):
            totalUnknown += 1
        romSection = RomSection(filename, str(fileEntry.PathHash), str(fileEntry.DataOffset),
                                str(fileEntry.CompDataSize), str(fileEntry.DataSize))
        RomSections.append(romSection)
        count += 1

    totalUnpacked += (header.NrOfFiles * 16)

    RomSections.sort(key=operator.attrgetter("DataOffset"))

    for romSection in RomSections:
        if romSection.IsDuplicate:
            totalDuplicates += 1

    print("Unpacking " + str(len(RomSections)) + " files using " + str(num_threads) + " threads...")
    with ThreadPoolExecutor(max_workers=num_threads) as executor:
        future_to_section = {
            executor.submit(_unpack_section, bec_filename, filedir, rs): rs
            for rs in RomSections
        }
        completed = 0
        for future in as_completed(future_to_section):
            decompressed_size = future.result()
            totalUnpacked += decompressed_size
            completed += 1
            if completed % 500 == 0:
                print("Unpack progress: " + str(completed) + "/" + str(len(RomSections)))

    # Give unresolved files descriptive names (content tag + hash + extension).
    for romSection in RomSections:
        if romSection.FileName.startswith("unknown-"):
            _rename_unknown(filedir, romSection)

    for romSection in RomSections:
        dataLine = romSection.FileName + separator
        dataLine += str(romSection.PathHash) + separator
        dataLine += str(romSection.DataOffset) + separator
        dataLine += str(romSection.CompressedSize) + separator
        dataLine += str(romSection.DataSize) + "\n"
        output += dataLine

    print("Total unpacked was : " + str(totalUnpacked))
    print("Total duplicates was : " + str(totalDuplicates))
    print("Total unknown was : " + str(totalUnknown))

    return output


