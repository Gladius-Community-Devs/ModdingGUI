def ReadSection(file, addr, size):
    file.seek(addr)
    return file.read(size)


def WriteSectionInFile(fByteArray, dirname, filename):
    filename2 = dirname + filename
    dirpath = os.path.dirname(filename2)
    if dirpath:
        os.makedirs(dirpath, exist_ok=True)
    outFile = open(filename2, "wb")
    outFile.write(fByteArray)
    outFile.close()


def getFilename(hashcode, count):
    path = _hashes.lookup(hashcode)
    if path is not None:
        return path
    # Stable, hash-based placeholder (count is only the sort order, not meaningful).
    return "unknown-0x%08x.bin" % hashcode


# Map an unresolved file's magic/head bytes to a descriptive tag + extension so
# modders can at least see *what* an unresolved file is (script, texture pack,
# archive, mesh, bat, ...) even when its real internal path is unknown.
def _classify(head):
    if head[:4] == b"PTTP":
        return "pttp", ".ptx"
    if head[:4] == b"PAK1":
        return "pak", ".pak"
    if head[:4] == b"VERS":
        return "mesh", ".pax"
    if head[:4] == b"BNR1":
        return "banner", ".bnr"
    if head[:4] == b" ceb":
        return "bec", ".bec"
    if (b"function" in head or b"OnInit" in head
            or b"MODLEVELRANGESKILL" in head or b"MODITEMSCOMP" in head
            or b"MODCORESTATSCOMP" in head):
        return "script", ".scp"
    if (b"@echo" in head or b"buildpak" in head or b"tpager" in head
            or b"ptxutil" in head or b"REM --" in head):
        return "bat", ".bat"
    if b"//Saved School" in head or b"NAME:" in head:
        return "school", ".tok"
    if head and all(32 <= b < 127 or b in (9, 10, 13) for b in head):
        return "text", ".txt"
    return "bin", ".bin"


def _rename_unknown(filedir, romSection):
    """Rename an unresolved file to a descriptive ``unknown-<tag>-0x<hash>.<ext>``
    name so its content type is visible without knowing its real path."""
    old = os.path.join(filedir, romSection.FileName)
    try:
        with open(old, "rb") as f:
            head = f.read(600)
    except OSError:
        return
    tag, ext = _classify(head)
    newname = "unknown-%s-0x%08x%s" % (tag, romSection.PathHash, ext)
    new = os.path.join(filedir, newname)
    if new != old:
        try:
            os.replace(old, new)
            romSection.FileName = newname
        except OSError:
            pass


