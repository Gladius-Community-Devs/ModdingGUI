def computeFileHash(name):
    length = len(name)
    hashVal = 0
    i = 0
    while length > 0:
        currentChar = ord(name[i])
        lookupKey = (hashVal ^ currentChar) & 0xff
        hashVal = CRCTable[lookupKey] ^ (hashVal >> 8)
        length -= 1
        i += 1
    return hashVal


def computeDataChecksum(data):
    """CRC-32 of ``data`` without the usual pre/post inversion.

    Byte-for-byte the same result as the table loop this replaces - the loop is exactly
    ``zlib.crc32(data, 0xFFFFFFFF) ^ 0xFFFFFFFF`` - but zlib's C implementation does ~500 MB/s
    instead of ~5 MB/s, and this is the only real hot spot in a pack: 24,453 calls over 456 MB
    took 92 of the 103 seconds (profiled), which is why a v008 pack felt slower than v007 even
    though v008 removed the per-file flush().
    """
    return zlib.crc32(data, 0xFFFFFFFF) ^ 0xFFFFFFFF


