def _load_and_compress(item, dir, compress):
    item.OldSize = item.DataSize
    filepath = normpath(dir + "/" + item.FileName)
    item.DataSize = os.path.getsize(filepath)

    with open(filepath, "rb") as f:
        filedata = bytearray(f.read())

    if compress:
        compressedData = zlib.compress(filedata, 1)
        compressionRatio = 1.0
        if len(filedata) > 0:
            compressionRatio = float(len(compressedData)) / float(len(filedata))
        if compressionRatio < 0.9:
            filedata = compressedData
            item.CompressedSize = len(compressedData)
        else:
            item.CompressedSize = 0
    else:
        item.CompressedSize = 0

    item.FileByteArray = filedata

    if item.OldSize != item.DataSize:
        print(item.FileName + " size changed : " + str(item.OldSize) + " / " + str(item.DataSize))


def createBecArchive(dir, filename, becmap, demobec=False, platform="GC", num_threads=None,
                     ignore_checksum=False):
    print("createBecArchive")
    FileAlignment = 0x0
    HeaderMagic = 0x0
    output = ""
    TotalFileLength = 0

    if num_threads is None:
        num_threads = NUM_THREADS

    readfileListResults = readFileList(becmap)
    FileAlignment = readfileListResults[1]
    HeaderMagic = readfileListResults[2]

    print("Platform is : " + platform)

    compress = False
    includeUncompressed = False

    if platform == "XBOX" or platform == "PS2":
        compress = True
    if platform == "PS2":
        includeUncompressed = True

    print("compress is set to : " + str(compress))

    RomMap = list(readfileListResults[0])

    # Files listed in the manifest but deleted from the folder are removed from
    # the mod (with a loud warning) rather than aborting the whole pack.
    removedFiles = readfileListResults[4]
    if removedFiles:
        removedSet = set(removedFiles)
        RomMap = [item for item in RomMap if item.FileName not in removedSet]
        for name in removedFiles:
            print("WARNING: removing file from mod (deleted from folder): " + name)

    # include any new files
    RomMap.extend(readfileListResults[3])

    if os.path.dirname(filename) != "":
        if not os.path.exists(os.path.dirname(filename)):
            os.makedirs(os.path.dirname(filename))
    output_rom = open(filename, "wb")

    ignoreChecksumVersion = 0x1
    useChecksumVersion = 0x3
    version = useChecksumVersion
    if ignore_checksum:
        version = ignoreChecksumVersion

    NrOfFiles = len(RomMap)

    output += str(FileAlignment) + separator + str(NrOfFiles) + separator + str(HeaderMagic) + "\n"

    print("Creating file with : " + str(NrOfFiles) + " entries and file alignment : " + str(FileAlignment))

    output_rom.write(struct.pack("<4sHHII", b" ceb", int(version), int(FileAlignment),
                                 int(NrOfFiles), int(HeaderMagic)))

    addr = 0x10 + NrOfFiles * 0x10
    addr += (FileAlignment - 1)
    addr &= (0x100000000 - FileAlignment)

    print("After header position : " + str(output_rom.tell()))
    print("Start address : " + str(addr))

    baseAddr = addr
    currentAddr = baseAddr

    # Primary copy precedes duplicates sharing the same DataOffset.
    RomMap.sort(key=lambda x: (x.DataOffset, 1 if x.IsDuplicate else 0))

    print("Sorted Offset")

    print("Loading and compressing " + str(len(RomMap)) + " files using " + str(num_threads) + " threads...")
    with ThreadPoolExecutor(max_workers=num_threads) as executor:
        futures = [executor.submit(_load_and_compress, item, dir, compress) for item in RomMap]
        completed = 0
        for future in as_completed(futures):
            future.result()
            completed += 1
            if completed % 500 == 0:
                print("Load/compress progress: " + str(completed) + "/" + str(len(RomMap)))

    # Phase 2: sequential offset computation (duplicate detection depends on the
    # previous item's OriginalDataOffset).
    lastItem = None
    for item in RomMap:
        duplicate = False

        if lastItem is not None:
            if lastItem.OriginalDataOffset == item.OriginalDataOffset and item.IsNew is False:
                duplicate = True

        if duplicate:
            item.CompressedSize = lastItem.CompressedSize | duplicateFlag
            item.DataOffset = lastItem.DataOffset
        else:
            if item.IsNew:
                print("Adding new item " + item.FileName + " at position " + str(currentAddr))

            item.DataOffset = currentAddr

            currentAddr += item.storedSize()
            currentAddr += (FileAlignment - 1)
            currentAddr += checksumSize

            currentAddr &= (0x100000000 - FileAlignment)

            if includeUncompressed and item.unpackedCompressedSize() > 0:
                currentAddr += item.DataSize
                currentAddr += (FileAlignment - 1)
                currentAddr &= (0x100000000 - FileAlignment)

        TotalFileLength += item.DataSize
        lastItem = item

    RomMap.sort(key=operator.attrgetter("PathHash"))
    for item in RomMap:
        output_rom.write(struct.pack("<I", item.PathHash))
        output_rom.write(struct.pack("<I", item.DataOffset))
        output_rom.write(struct.pack("<I", item.CompressedSize))
        output_rom.write(struct.pack("<I", item.DataSize))

        dataLine = item.FileName + separator
        dataLine += str(item.PathHash) + separator
        dataLine += str(item.DataOffset) + separator
        dataLine += str(item.CompressedSize) + separator
        dataLine += str(item.DataSize) + "\n"
        output += dataLine

    alignFileSizeWithZeros(output_rom, output_rom.tell(), FileAlignment)

    print("After header write and align : " + str(output_rom.tell()))
    print("RomMap Size : " + str(len(RomMap)))

    RomMap.sort(key=operator.attrgetter("DataOffset"))
    i = 0
    lastItem = None
    for item in RomMap:
        currentPosition = output_rom.tell()

        # entries that shared the same offset were already written
        if item.DataOffset < currentPosition:
            lastItem = item
            continue

        output_rom.write(item.FileByteArray)

        if item.storedSize() > 0:
            output_rom.write(struct.pack("<II", computeDataChecksum(item.FileByteArray), 0))
        else:
            output_rom.write(b"\0" * FileAlignment)

        alignFileSizeWithZeros(output_rom, output_rom.tell(), FileAlignment)

        if includeUncompressed and item.unpackedCompressedSize() > 0:
            uncompressedFileArray = zlib.decompress(item.FileByteArray)
            output_rom.write(uncompressedFileArray)
            alignFileSizeWithZeros(output_rom, output_rom.tell(), FileAlignment)

        if item.OldSize != item.DataSize:
            print("Adding new file " + item.FileName + " hash " + str(item.PathHash)
                  + " with dataoffset + " + str(item.DataOffset) + " size " + str(item.DataSize))

        i += 1
        if (i % 2500) == 0:
            print("write progress... " + str(i) + "/" + str(len(RomMap)))
        lastItem = item

    output_rom.close()

    print("Total data packed : " + str(TotalFileLength))

    # Persist the mod manifest so added/removed files are stable across runs.
    # repack-filelist.txt is the source of truth for the mod's contents; the
    # vanilla filelist.txt is left untouched. It is listed in SKIP_FILES so it
    # is never packed into the archive itself.
    _write_repack_filelist(dir, output)

    return output


def _write_repack_filelist(dir, output):
    try:
        path = os.path.join(dir, repackFile)
        parent = os.path.dirname(path)
        if parent and not os.path.exists(parent):
            os.makedirs(parent)
        with open(path, "w") as f:
            f.write(output)
    except OSError as exc:
        print("WARNING: could not write " + repackFile + ": " + str(exc))


def _load_manifest(dir):
    """Return ``(alignment, magic, [(name, hash, offset, compsize, datasize)])``.

    Prefers the mod manifest (repack-filelist.txt); falls back to the vanilla
    filelist.txt when no manifest has been written yet.
    """
    base = os.path.join(dir, repackFile)
    if not os.path.exists(base):
        base = os.path.join(dir, headerFile)

    alignment, magic = 0, 0
    entries = []
    if os.path.exists(base):
        with open(base, encoding="utf-8", errors="replace") as fin:
            lines = fin.read().splitlines()
            if lines:
                try:
                    parts = lines[0].split(separator)
                    alignment, magic = int(parts[0]), int(parts[2])
                except (ValueError, IndexError):
                    pass
                for ln in lines[1:]:
                    if not ln.strip() or ln.startswith("#"):
                        continue
                    fields = ln.split(separator)
                    if len(fields) >= 2:
                        entries.append(fields[:5])
    return alignment, magic, entries


def _save_manifest(dir, alignment, magic, entries):
    out = "%d%s%d%s%d\n" % (alignment, separator, len(entries), separator, magic)
    out += "\n".join(separator.join(str(x) for x in e) for e in entries) + "\n"
    path = os.path.join(dir, repackFile)
    with open(path, "w", encoding="utf-8") as f:
        f.write(out)


def add_file_to_bec(dir, host_file, bec_path, hash_value=None):
    """Copy ``host_file`` into the BEC folder at ``bec_path`` and record it in the
    mod manifest, keyed by ``hash_value`` (or the CRC-32 of the path by default).

    Lets a modder add content the game looks up by a known hash even when the
    original path string is unknown (e.g. one of the unresolved ``unknown-NNN``
    slots). The file becomes part of the archive on the next pack.
    """
    dir = os.path.abspath(dir)
    name = bec_path.replace("\\", "/").lower().lstrip("/")
    target = os.path.join(dir, name)
    parent = os.path.dirname(target)
    if parent and not os.path.exists(parent):
        os.makedirs(parent)
    shutil.copyfile(host_file, target)

    h = int(hash_value) if hash_value is not None else computeFileHash(name)

    alignment, magic, entries = _load_manifest(dir)
    entries = [e for e in entries if e[0].lower() != name]
    entries.append([name, h, fileAtEnd, 0, 0])
    _save_manifest(dir, alignment, magic, entries)

    print("Added %s (hash %d) to the mod manifest." % (name, h))
    print("Run a pack to include it in the rebuilt archive.")
    return h


def refresh_filelist(dir):
    """Recompute the mod manifest (adds/removes) without packing, so a user can
    preview exactly what will be in the next archive."""
    dir = os.path.abspath(dir)
    results = readFileList(os.path.join(dir, headerFile))
    fileListData, alignment, magic, newFiles, removedFiles = results

    entries = []
    removedSet = set(removedFiles)
    for item in fileListData:
        if item.FileName in removedSet:
            continue
        entries.append([item.FileName, item.PathHash, item.DataOffset,
                        item.CompressedSize, item.DataSize])
    for item in newFiles:
        entries.append([item.FileName, item.PathHash, item.DataOffset,
                        item.CompressedSize, item.DataSize])

    _save_manifest(dir, alignment, magic, entries)

    print("Manifest refreshed: %d files (added %d, removed %d)."
          % (len(entries), len(newFiles), len(removedFiles)))
    if removedFiles:
        for name in removedFiles:
            print("  removed: " + name)
    if newFiles:
        for item in newFiles:
            print("  added:   " + item.FileName + " (hash " + str(item.PathHash) + ")")
